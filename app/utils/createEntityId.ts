/**
 * Собирает уникальный ключ записи формы — активного эффекта, блока заклинаний
 * существа и всего, что живёт в JSONB и должно пережить переименование.
 *
 * Через `crypto.randomUUID`, а когда его нет — временем и случайным хвостом:
 * метод требует защищённого контекста, и на серверном рендере старых сборок
 * или по обычному http его может не оказаться. Ключ нужен всегда, поэтому
 * запасной вариант считается достаточным: столкнуться двум записям одной формы
 * в одну миллисекунду с одним хвостом практически невозможно.
 *
 * @param prefix приставка ключа: по ней в данных видно, чей это ключ.
 * @returns ключ вида `effect-<uuid>`.
 */
export function createEntityId(prefix: string): string {
  if (typeof crypto !== 'undefined' && 'randomUUID' in crypto) {
    return `${prefix}-${crypto.randomUUID()}`;
  }

  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
}
