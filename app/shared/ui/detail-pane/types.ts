/** Соседи открытой записи в списке раздела — для листания в панели. */
export interface DetailPaneNeighbours {
  /** Адрес предыдущей записи; нет — открыта первая */
  previousUrl: string | undefined;
  /** Адрес следующей записи; нет — открыта последняя из загруженных */
  nextUrl: string | undefined;
  /** Номер открытой записи в списке, с единицы */
  position: number;
  /** Сколько записей в загруженном списке */
  total: number;
}
