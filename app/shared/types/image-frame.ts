/**
 * Кадр обложки: какая часть картинки видна в квадрате на странице записи и в
 * карточке списка. Сам файл не обрезается — при просмотре целиком видна вся
 * картинка.
 */
export interface ImageFrame {
  /** Точка фокуса по горизонтали: доля ширины картинки от 0 до 1. */
  x: number;

  /** Точка фокуса по вертикали: доля высоты картинки от 0 до 1. */
  y: number;

  /** Приближение: 1 — картинка заполняет рамку, больше — ближе. */
  zoom: number;
}
