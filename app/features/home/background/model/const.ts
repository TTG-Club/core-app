/**
 * Минимальное количество частиц на экране
 */
export const PARTICLES_MIN_COUNT = 10;

/**
 * Делитель для расчёта количества частиц на основе площади экрана.
 * Формула: (ширина * высота) / PARTICLES_DENSITY_DIVIDER.
 * Плотность вдвое ниже прежней (делитель 12000): при полной частицы рябили
 * вокруг текста.
 */
export const PARTICLES_DENSITY_DIVIDER = 24000;

/**
 * Минимальный радиус частицы в пикселях.
 * Размеры вернулись к исходным 0.5–1.5: укрупнённые при редизайне главной
 * 0.7–2.2 читались пятнами, а не пылью.
 */
export const PARTICLE_SIZE_MIN = 0.5;

/**
 * Максимальный радиус частицы в пикселях
 */
export const PARTICLE_SIZE_MAX = 1.5;

/**
 * Минимальная скорость движения частицы по оси Y (пикселей за кадр).
 * Обе границы втрое ниже исходных 0.2–0.7 (сперва на треть, затем ещё
 * вдвое): частицы должны плыть фоном, а не тянуть взгляд на себя. Их же
 * читает профиль — настройка одна на все страницы с частицами.
 */
export const PARTICLE_SPEED_MIN = 0.065;

/**
 * Максимальная скорость движения частицы по оси Y (пикселей за кадр)
 */
export const PARTICLE_SPEED_MAX = 0.235;

/**
 * Минимальная прозрачность частицы (0-1)
 */
export const PARTICLE_OPACITY_MIN = 0.35;

/**
 * Максимальная прозрачность частицы (0-1)
 */
export const PARTICLE_OPACITY_MAX = 0.9;
