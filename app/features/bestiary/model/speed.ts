/**
 * Строка скорости существа для показа.
 *
 * Бэкенд склеивает её из отдельных скоростей и оставляет перед запятыми лишние
 * пробелы («30 фт., летая 60 фт. , плавая 30 фт.») — в карточке это видно как
 * разрыв между точкой и запятой. Чистим на выводе: данные в справочнике от
 * этого не меняются, и правка одинаково работает и для уже заведённых существ.
 *
 * @param speed строка скорости из ответа карточки существа.
 * @returns та же строка без пробелов перед знаками препинания и без двойных
 *   пробелов внутри.
 */
export function formatCreatureSpeed(speed: string): string {
  return speed
    .replace(/\s+([,;])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();
}
