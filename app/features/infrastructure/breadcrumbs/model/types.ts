/** Описание раздела сайта для хлебных крошек */
export interface BreadcrumbRoute {
  /** Название раздела в крошках */
  label: string;
  /**
   * `false`, если у пути нет собственной страницы (например, `/tools`) —
   * такая крошка показывается текстом, без ссылки.
   */
  navigable?: boolean;
}
