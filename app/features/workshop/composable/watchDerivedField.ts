import type { Ref } from 'vue';

/**
 * Записывает в модель производное значение (пересчитанное по формуле) только
 * тогда, когда изменение вызвано правкой пользователя.
 *
 * Формы мастерской подменяют объект состояния целиком: загрузка записи из
 * `/raw`, применение ревизии, сброс после сохранения. Обычный вотчер видит это
 * как изменение источников и молча перетирает сохранённое значение формулой —
 * так инициатива сатира (+3) превращалась в +5 сразу при открытии формы.
 * Срабатывания, в которых объект модели заменился, пропускаются: пересчёт идёт
 * только пока пользователь работает с одной и той же записью.
 *
 * `watchIgnorable` и `watchPausable` из VueUse тут не подходят: паузу должен
 * ставить тот, кто грузит запись, а форма и поля живут в разных компонентах.
 *
 * @param model модель поля из `defineModel`.
 * @param derived геттер производного значения.
 * @param apply запись значения в модель; вызывается только для правок пользователя.
 */
export function watchDerivedField<TModel extends object, TValue>(
  model: Ref<TModel>,
  derived: () => TValue,
  apply: (value: TValue, model: TModel) => void,
): void {
  watch(
    // Сравниваем «сырые» объекты: у реактивных прокси другая идентичность, и
    // сверять их через `!==` небезопасно. Значение при этом записываем в
    // `model.value` — запись в raw-объект не запустила бы реактивность.
    [() => toRaw(model.value), derived],
    ([nextModel, value], [previousModel]) => {
      if (nextModel !== previousModel) {
        return;
      }

      apply(value, model.value);
    },
  );
}
