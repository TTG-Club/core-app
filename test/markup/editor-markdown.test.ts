import { describe, expect, it } from 'vitest';

// Прямо из модуля: наружу домена хелпер не экспортируется (им пользуется только
// сериализатор), а баррел `~ui/markup` тянет SFC — окружение тестов их не грузит.
import { unescapeEditorMarkdown } from '~ui/markup/editor-markdown';

/**
 * Визуальный редактор отдаёт исходник через @tiptap/markdown, а тот экранирует
 * парные символы Markdown (`\~`, `\*`) и кодирует `&`/`<`/`>` сущностями. Наш
 * рендер Markdown не разбирает и напечатал бы это буквально, поэтому на границе
 * хранения экранирование снимается (`toStoredMarkup`).
 */
describe('снятие экранирования @tiptap/markdown', () => {
  it.each([
    ['сло\\~во', 'сло~во'],
    ['зелье &amp; свиток', 'зелье & свиток'],
    ['&lt;тег&gt;', '<тег>'],
    ['\\*звёздочка\\*', '*звёздочка*'],
    ['\\[скобки\\]', '[скобки]'],
    ['\\`бэктик\\`', '`бэктик`'],
    ['{@b сло\\~во}', '{@b сло~во}'],
  ])('возвращает литеральные символы: %s', (source, expected) => {
    expect(unescapeEditorMarkdown(source)).toBe(expected);
  });

  it('снимает экранирование одним проходом', () => {
    // Автор написал слеш и тильду: остаться должен ровно `\~`.
    expect(unescapeEditorMarkdown('\\\\\\~')).toBe('\\~');
    // Автор написал саму сущность: остаться должна ровно она.
    expect(unescapeEditorMarkdown('&amp;amp;')).toBe('&amp;');
  });

  it('не трогает маркер пустого абзаца и обычный текст', () => {
    expect(unescapeEditorMarkdown('&nbsp;')).toBe('&nbsp;');
    expect(unescapeEditorMarkdown('обычный текст')).toBe('обычный текст');
  });
});
