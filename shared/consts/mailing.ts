/**
 * Общий контракт инструмента рассылки промокодов: маркеры письма и лимиты.
 * Лежит в `shared`, потому что одни и те же значения нужны и админской форме
 * (валидация, подсказки, нарезка на запросы), и серверным роутам рассылки.
 */

/** Маркер в тексте письма, вместо которого подставляется промокод получателя. */
export const MAILING_CODE_PLACEHOLDER = '{{code}}';

/** Маркер в тексте письма, вместо которого подставляется адрес получателя. */
export const MAILING_EMAIL_PLACEHOLDER = '{{email}}';

/**
 * Сколько получателей уходит на сервер за один запрос. Маленькая пачка держит
 * запрос коротким (не упирается в таймауты прокси), даёт живой прогресс в UI и
 * не выедает лимит 75 запросов в минуту на `/api/**` даже на полной рассылке.
 */
export const MAILING_CHUNK_SIZE = 5;

/** Потолок получателей одной рассылки. */
export const MAILING_RECIPIENTS_MAX = 200;

/**
 * Пауза между письмами внутри одного запроса, мс. Ровный темп «не чаще письма
 * в секунду» — базовая гигиена рассылки, чтобы почтовые провайдеры не считали
 * отправку всплеском спама.
 */
export const MAILING_SEND_DELAY_MS = 1000;

/**
 * Предел длины метки кода: колонка `label` в subscriber-service — VARCHAR(255).
 * В метку попадает и название рассылки, и адрес получателя.
 */
export const MAILING_CODE_LABEL_MAX_LENGTH = 255;

/** Разделитель названия рассылки и адреса получателя в метке кода. */
export const MAILING_LABEL_SEPARATOR = ' · ';

/** Название рассылки по умолчанию — попадает в метку выпущенных кодов. */
export const MAILING_DEFAULT_LABEL = 'Рассылка';

/** Код-образец для тестового письма: реальный код при этом не выпускается. */
export const MAILING_SAMPLE_CODE = 'ABCD2345EFGH6789';

/** Предел длины темы письма. */
export const MAILING_SUBJECT_MAX_LENGTH = 200;

/** Предел длины текста письма. */
export const MAILING_BODY_MAX_LENGTH = 5000;

/** Предел длины названия рассылки. */
export const MAILING_LABEL_MAX_LENGTH = 120;
