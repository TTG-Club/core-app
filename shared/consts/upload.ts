/**
 * Допустимые типы загружаемых изображений. Лежит в `shared`: один и тот же
 * список проверяет браузер до отправки и сервер в роутах загрузки.
 */
export const IMAGE_UPLOAD_TYPES = ['image/jpeg', 'image/png', 'image/webp'];

/**
 * Максимальный вес исходной картинки, байт (7 МБ). Это лимит на то, что
 * выбирает пользователь: сервер всё равно пережимает файл в WebP.
 */
export const IMAGE_UPLOAD_MAX_WEIGHT = 7 * 1024 * 1024;

/**
 * Префикс ссылок на файлы хранилища сайта: ссылка — это префикс и ключ
 * объекта. Сервер строит по нему ссылки, а сервер и браузер отбрасывают
 * ссылки на аватарки с чужих адресов.
 */
export const S3_URL_PREFIX = '/s3/';

/**
 * Раздел хранилища для картинок в ответах команды на баг-репорты. Общий для
 * браузера (редактор ответа называет его при загрузке) и сервера (по нему
 * загрузка узнаёт командный раздел).
 */
export const BUG_REPORT_REPLY_IMAGE_SECTION = 'bug-report-replies';

/**
 * Командные разделы хранилища: файлы в них лежат в общей папке команды, а не в
 * папке того, кто их загрузил. Адрес файла из такого раздела не выдаёт логин
 * сотрудника — ответ на баг-репорт автор видит без имени ответившего.
 */
export const S3_TEAM_SECTIONS: readonly string[] = [
  BUG_REPORT_REPLY_IMAGE_SECTION,
];

/** Папка команды в командных разделах хранилища — вместо логина загрузившего. */
export const S3_TEAM_FOLDER = 'team';
