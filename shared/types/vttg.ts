/**
 * Сборка VTTG, которую можно скачать. Идентификатор описывает платформу целиком:
 * ОС, архитектуру и роль (десктоп или сервер) — файлы под разные арки не
 * взаимозаменяемы, внутри лежат нативные бинарники под конкретную.
 */
export type VttgBuildId =
  | 'windows-x64'
  | 'mac-arm64'
  | 'linux-x64'
  | 'linux-arm64'
  | 'server-linux-x64'
  | 'server-linux-arm64'
  | 'docker';

/** Файл сборки: у Linux-десктопа их два (AppImage и deb), у остальных один. */
export interface VttgBuildFile {
  /** Формат файла — он же подпись кнопки, когда файлов несколько. */
  format: string;
  /** Имя файла в канале обновлений. */
  fileName: string;
  /** Прямая ссылка на файл. */
  downloadUrl: string;
  /** Размер в байтах — `null`, если манифест его не отдал. */
  size: number | null;
}

/**
 * Состояние одной сборки в канале обновлений. Версии у сборок свои: платформы
 * выкатываются разными workflow и с задержкой, поэтому общей версии у VTTG нет.
 *
 * Пустой `files` (и `version: null`) означает «сборка ещё не опубликована» —
 * в интерфейсе это выключенная кнопка «Скоро». Ошибка чтения манифеста выглядит
 * так же: пока файла нет, канал отвечает на него 403.
 */
export interface VttgBuild {
  id: VttgBuildId;
  /** Версия сборки, например `0.9.327`. */
  version: string | null;
  /** Дата публикации (ISO) — `null`, если её нет в манифесте. */
  releaseDate: string | null;
  files: VttgBuildFile[];
}
