/** Последняя опубликованная сборка десктопного VTTG (канал обновлений). */
export interface VttgDesktopRelease {
  /** Версия сборки, например `0.9.273`. */
  version: string;
  /** Имя файла установщика в канале обновлений. */
  fileName: string;
  /** Прямая ссылка на установщик последней версии. */
  downloadUrl: string;
  /** Размер установщика в байтах — `null`, если манифест его не отдал. */
  size: number | null;
  /** Дата публикации сборки (ISO) — `null`, если её нет в манифесте. */
  releaseDate: string | null;
}
